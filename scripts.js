var language = "pt";
var light = false;

var themeButton = document.querySelector(".theme-button");
var flowerImage = document.querySelector(".flower-image");
var menuButton = document.querySelector(".menu-button");
var navLinks = document.querySelector(".nav-links");
var form = document.querySelector(".contact-form");
var formSuccess = document.getElementById("formSuccess");
var ptButton = document.getElementById("ptButton");
var enButton = document.getElementById("enButton");

function changeLanguage() {
  var text = translations[language];
  var elements = document.querySelectorAll("[data-i18n]");

  for (var i = 0; i < elements.length; i++) {
    var key = elements[i].getAttribute("data-i18n");
    elements[i].textContent = text[key];
  }

  document.getElementById("name").placeholder = text.namePlaceholder;
  document.getElementById("email").placeholder = text.emailPlaceholder;
  document.getElementById("subject").placeholder = text.subjectPlaceholder;
  document.getElementById("message").placeholder = text.messagePlaceholder;

  document.documentElement.lang = language === "pt" ? "pt-BR" : "en";

  ptButton.classList.remove("language-active");
  enButton.classList.remove("language-active");

  if (language === "pt") {
    ptButton.classList.add("language-active");
  } else {
    enButton.classList.add("language-active");
  }

  changeTheme();
}

function changeTheme() {
  if (light) {
    document.documentElement.classList.add("light");
    flowerImage.src = "flores-light.webp";
    themeButton.querySelector("span:last-child").textContent = translations[language].themeLight;
  } else {
    document.documentElement.classList.remove("light");
    flowerImage.src = "flores-dark.webp";
    themeButton.querySelector("span:last-child").textContent = translations[language].themeDark;
  }
}

themeButton.addEventListener("click", function () {
  light = !light;
  changeTheme();
});

ptButton.addEventListener("click", function () {
  language = "pt";
  changeLanguage();
});

enButton.addEventListener("click", function () {
  language = "en";
  changeLanguage();
});

menuButton.addEventListener("click", function () {
  menuButton.classList.toggle("open");
  navLinks.classList.toggle("menu-open");
});

navLinks.addEventListener("click", function (event) {
  if (event.target.tagName === "A") {
    navLinks.classList.remove("menu-open");
    menuButton.classList.remove("open");
  }
});

function showError(id, message) {
  document.getElementById(id + "Error").textContent = message;
}

formSuccess.hidden = true;

form.addEventListener("submit", async function (event) {
  event.preventDefault();

  var text = translations[language];

  var name = document.getElementById("name").value.trim();
  var email = document.getElementById("email").value.trim();
  var subject = document.getElementById("subject").value.trim();
  var message = document.getElementById("message").value.trim();

  var emailPattern = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
  var hasError = false;

  showError("name", "");
  showError("email", "");
  showError("subject", "");
  showError("message", "");

  formSuccess.hidden = true;

  if (name.length < 2 || name.length > 100) {
    showError("name", text.required);
    hasError = true;
  }

  if (!emailPattern.test(email) || email.length > 255) {
    showError("email", text.required);
    hasError = true;
  }

  if (subject.length < 3 || subject.length > 120) {
    showError("subject", text.required);
    hasError = true;
  }

  if (message.length < 10 || message.length > 1200) {
    showError("message", text.required);
    hasError = true;
  }

  if (hasError) {
    return;
  }

  var formData = new FormData(form);

  try {
    var response = await fetch(
      "https://formsubmit.co/ajax/" + form.action.split("https://formsubmit.co/")[1],
      {
        method: "POST",
        body: formData,
        headers: {
          Accept: "application/json"
        }
      }
    );

    var result = await response.json();

    if (result.success === "true" || result.success === true) {
      form.reset();
      formSuccess.hidden = false;
    } else {
      alert("Não foi possível enviar a mensagem. Tente novamente.");
    }

  } catch (error) {
    alert("Não foi possível enviar a mensagem. Verifique sua conexão e tente novamente.");
  }
});

var tabs = document.querySelectorAll(".tab");
var contents = document.querySelectorAll(".tab-content");

for (var i = 0; i < tabs.length; i++) {

  tabs[i].addEventListener("click", function () {

    for (var j = 0; j < tabs.length; j++) {
      tabs[j].classList.remove("active");
    }

    for (var j = 0; j < contents.length; j++) {
      contents[j].classList.remove("show");
    }

    this.classList.add("active");

    var id = this.getAttribute("data-tab");
    document.getElementById(id).classList.add("show");
  });

}

